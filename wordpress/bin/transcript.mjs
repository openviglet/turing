// The demo video's transcript (T1257): what Ana says, from demo/narration/script.json, for the
// pages that show the video. Search and assistants read text, not video.
//
// Writes:
//   frontend/apps/site/src/lib/wordpress-transcript.ts     WORDPRESS_TRANSCRIPT[language]: paragraphs
//   the block between the transcript markers in
//   frontend/apps/docs/src/content/docs/integrations/wordpress/index.md
//
// The script carries voice directions for the narration ("[excited]", "[laughs]"); they are not
// words Ana says, so they are dropped. Run after editing the script: `npm run transcript`.
// `--check` writes nothing and exits 1 when either output is out of date.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join( dirname( fileURLToPath( import.meta.url ) ), '..' );
const repo = join( root, '..' );
const check = process.argv.includes( '--check' );

const LANGUAGES = [
	[ 'pt-BR', 'Português' ],
	[ 'en', 'English' ],
];
const START =
	'<!-- transcript:start (generated by wordpress/bin/transcript.mjs) -->';
const END = '<!-- transcript:end -->';

const script = JSON.parse(
	readFileSync( join( root, 'demo', 'narration', 'script.json' ), 'utf8' )
);

/**
 * A line as said: no voice directions, single spaces.
 *
 * @param {string} line A narration line.
 */
const spoken = ( line ) =>
	line
		.replace( /\[[^\]]*\]/g, '' )
		.replace( /\s+/g, ' ' )
		.trim();

/**
 * Every line of one language, in the order the video says them.
 *
 * @param {string} language A script language, e.g. pt-BR.
 */
function transcript( language ) {
	const parts = [ script.intro ];
	for ( const key of Object.keys( script.chapters ).sort(
		( a, b ) => Number( a ) - Number( b )
	) ) {
		parts.push(
			script.chapters[ key ].card,
			script.chapters[ key ].result
		);
	}
	parts.push( script.outro );
	return parts
		.map( ( part ) => spoken( part?.[ language ] ?? '' ) )
		.filter( Boolean );
}

const byLanguage = Object.fromEntries(
	LANGUAGES.map( ( [ language ] ) => [ language, transcript( language ) ] )
);

const outputs = [];

const module = join(
	repo,
	'frontend',
	'apps',
	'site',
	'src',
	'lib',
	'wordpress-transcript.ts'
);
outputs.push( [
	module,
	[
		'// Generated by wordpress/bin/transcript.mjs from wordpress/demo/narration/script.json (T1257).',
		'// Do not edit: change the script and run `npm run transcript` in wordpress/.',
		`export const WORDPRESS_TRANSCRIPT: Record<string, string[]> = ${ JSON.stringify(
			byLanguage,
			null,
			2
		) };`,
		'',
	].join( '\n' ),
] );

const docs = join(
	repo,
	'frontend',
	'apps',
	'docs',
	'src',
	'content',
	'docs',
	'integrations',
	'wordpress',
	'index.md'
);
const page = readFileSync( docs, 'utf8' );
const from = page.indexOf( START );
const to = page.indexOf( END );
if ( from < 0 || to < from ) {
	process.stderr.write( `${ docs } has no transcript markers\n` );
	process.exit( 1 );
}
const block = [
	START,
	...LANGUAGES.flatMap( ( [ language, label ] ) => [
		'',
		`<details>`,
		`<summary>Transcript (${ label })</summary>`,
		'',
		...byLanguage[ language ].flatMap( ( paragraph ) => [ paragraph, '' ] ),
		`</details>`,
	] ),
	'',
	END,
].join( '\n' );
outputs.push( [
	docs,
	page.slice( 0, from ) + block + page.slice( to + END.length ),
] );

let stale = 0;
for ( const [ path, content ] of outputs ) {
	let current = '';
	try {
		current = readFileSync( path, 'utf8' );
	} catch {}
	if (
		current.replace( /\r\n/g, '\n' ) === content.replace( /\r\n/g, '\n' )
	) {
		continue;
	}
	if ( check ) {
		process.stderr.write(
			`${ path } is out of date: run npm run transcript\n`
		);
		stale++;
	} else {
		writeFileSync( path, content );
		process.stdout.write( `wrote ${ path }\n` );
	}
}
process.exit( stale ? 1 : 0 );
