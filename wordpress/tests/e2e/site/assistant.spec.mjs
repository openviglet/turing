// The Site assistant (D175): a button opening a chat with Turing over the site's posts. Turing's
// chat is answered with fixed streams so the suite needs no LLM; what the block does with a
// real one is ai/assistant.spec.mjs. The page holding the block is made here and removed again.
import { wp } from '../global-setup.mjs';
import { expect, test } from '../fixtures.mjs';

let pageId = 0;

test.describe.configure( { mode: 'serial' } );

test.beforeAll( () => {
	pageId = Number(
		wp( [
			'post',
			'create',
			'--post_type=page',
			'--post_status=publish',
			'--post_title=Ask us',
			'--post_content=<!-- wp:viglet-dumont/assistant {"suggestions":"When does the grant close?\\nWhere is the meeting?"} /-->',
			'--meta_input={"_viglet_dumont_exclude":"1"}',
			'--porcelain',
		] ).trim()
	);
} );

test.afterAll( () => {
	launcher( false );
	if ( pageId ) {
		wp( [ 'post', 'delete', String( pageId ), '--force' ] );
	}
} );

/**
 * Turn "Site assistant on every page" on or off.
 *
 * @param {boolean} on The setting.
 */
function launcher( on ) {
	wp( [
		'eval',
		`$s = viglet_dumont_get_settings(); $s['assistant_launcher'] = ${
			on ? 1 : 0
		}; viglet_dumont_update_settings( $s );`,
	] );
}

/**
 * A chat stream as Turing sends it: one SSE `data:` line per event.
 *
 * @param {Array<Object>} events Tokens as `{content}`, the rest as `{type, content}`.
 */
function stream( events ) {
	return {
		status: 200,
		headers: { 'Content-Type': 'text/event-stream' },
		body: events
			.map( ( e ) => `data: ${ JSON.stringify( e ) }\n\n` )
			.join( '' ),
	};
}

/**
 * Answer Turing's chat: on, and each question with the next of these streams.
 *
 * @param {import('@playwright/test').Page} page    The page.
 * @param {Array<Array<Object>>}            answers One stream's events per question.
 * @return {{asked: Object[], signals: Object[], results: Object[]}} What the page sent.
 */
async function turing( page, answers ) {
	const sent = { asked: [], signals: [], results: [] };
	await page.route( '**/chat/enabled', ( route ) =>
		route.fulfill( { json: { enabled: true } } )
	);
	await page.route( '**/chat/conversation', ( route ) => {
		sent.asked.push( route.request().postDataJSON() );
		return route.fulfill( stream( answers.shift() || [] ) );
	} );
	await page.route( '**/answer/signal', ( route ) => {
		sent.signals.push( route.request().postDataJSON() );
		return route.fulfill( { status: 204 } );
	} );
	await page.route( '**/chat/client-tool-result', ( route ) => {
		sent.results.push( route.request().postDataJSON() );
		return route.fulfill(
			stream( [ { content: 'That page is not on this site.' } ] )
		);
	} );
	return sent;
}

const grantAnswer = ( seed ) => [
	{ content: 'Applications close on ' },
	{ content: '14 March 2026.' },
	{
		type: 'sources',
		content: JSON.stringify( [
			{
				sourceId: 'grant',
				title: 'Research grant 2026',
				url: `/?p=${ seed.postId }`,
			},
		] ),
	},
];

test( 'without Turing’s chat the assistant stays hidden', async ( {
	page,
} ) => {
	await page.route( '**/chat/enabled', ( route ) =>
		route.fulfill( { json: { enabled: false, reason: 'NO_GENAI' } } )
	);
	await page.goto( `/?page_id=${ pageId }` );
	await page.waitForLoadState( 'networkidle' );
	await expect( page.locator( '.viglet-dumont-assistant' ) ).toBeHidden();
} );

test( 'a question gets a streamed answer, the post it used and a follow-up in context', async ( {
	page,
	seed,
	look,
	axe,
} ) => {
	const sent = await turing( page, [
		grantAnswer( seed ),
		[ { content: 'Send the form to the Office of Research.' } ],
		[ { content: 'Hello again.' } ],
	] );
	await page.goto( `/?page_id=${ pageId }` );
	const block = page.locator( '.viglet-dumont-assistant' );
	await block.getByRole( 'button', { name: 'Ask this site' } ).click();

	const dialog = page.getByRole( 'dialog', { name: 'Ask this site' } );
	await expect( dialog ).toBeVisible();
	await expect( dialog.getByLabel( 'Your question' ) ).toBeFocused();
	await expect(
		dialog.getByText( 'Answers are generated by AI', { exact: false } )
	).toBeVisible();

	// A suggested first question, from the block's settings, asks it.
	await dialog
		.getByRole( 'button', { name: 'When does the grant close?' } )
		.click();
	const log = dialog.getByRole( 'log', { name: 'Conversation' } );
	await expect(
		log.locator( '.viglet-dumont-assistant__message' ).nth( 1 )
	).toContainText( 'Applications close on 14 March 2026.' );
	const source = log.getByRole( 'link', { name: 'Research grant 2026' } );
	await expect( source ).toHaveAttribute( 'href', `/?p=${ seed.postId }` );
	await expect(
		dialog.getByRole( 'button', { name: 'When does the grant close?' } )
	).toBeHidden();
	await look( 'assistant' );
	await axe( 'the Site assistant', {
		include: '.viglet-dumont-assistant__dialog',
	} );

	await log.getByRole( 'button', { name: 'Yes' } ).click();
	await expect( log.getByRole( 'status' ) ).toHaveText( 'Thank you.' );
	await expect.poll( () => sent.signals.length ).toBe( 1 );
	expect( sent.signals[ 0 ] ).toMatchObject( {
		signal: 'THUMBS_UP',
		query: 'When does the grant close?',
		conversationId: sent.asked[ 0 ].conversationId,
	} );

	// A follow-up carries the conversation so far, in the same conversation.
	await dialog
		.getByLabel( 'Your question' )
		.fill( 'And where do I send it?' );
	await dialog.getByRole( 'button', { name: 'Send' } ).click();
	await expect(
		log.locator( '.viglet-dumont-assistant__message' )
	).toHaveCount( 4 );
	expect( sent.asked[ 1 ].messages.map( ( m ) => m.role ) ).toEqual( [
		'user',
		'assistant',
		'user',
	] );
	expect( sent.asked[ 1 ].conversationId ).toBe(
		sent.asked[ 0 ].conversationId
	);

	// Escape closes it, and it opens again where it was.
	await page.keyboard.press( 'Escape' );
	await expect( dialog ).toBeHidden();
	await block.getByRole( 'button', { name: 'Ask this site' } ).click();
	await expect(
		log.locator( '.viglet-dumont-assistant__message' )
	).toHaveCount( 4 );

	// A new conversation starts empty, and Turing is told it is a new one.
	await dialog.getByRole( 'button', { name: 'New conversation' } ).click();
	await expect(
		log.locator( '.viglet-dumont-assistant__message' )
	).toHaveCount( 0 );
	await dialog.getByLabel( 'Your question' ).fill( 'Hi' );
	await dialog.getByRole( 'button', { name: 'Send' } ).click();
	await expect(
		log.locator( '.viglet-dumont-assistant__message' )
	).toHaveCount( 2 );
	expect( sent.asked[ 2 ].messages ).toEqual( [
		{ role: 'user', content: 'Hi' },
	] );
	expect( sent.asked[ 2 ].conversationId ).not.toBe(
		sent.asked[ 0 ].conversationId
	);
} );

test( 'the assistant opens pages of this site only', async ( {
	page,
	seed,
} ) => {
	const sent = await turing( page, [
		[
			{
				type: 'client_tool_call',
				content: JSON.stringify( {
					callId: 'away',
					name: 'navigate',
					args: JSON.stringify( { url: 'https://example.com/' } ),
				} ),
			},
		],
		[
			{
				type: 'client_tool_call',
				content: JSON.stringify( {
					callId: 'here',
					name: 'navigate',
					args: JSON.stringify( { url: `/?p=${ seed.postId }` } ),
				} ),
			},
		],
	] );
	await page.goto( `/?page_id=${ pageId }` );
	await page.getByRole( 'button', { name: 'Ask this site' } ).click();
	const dialog = page.getByRole( 'dialog', { name: 'Ask this site' } );

	await dialog.getByLabel( 'Your question' ).fill( 'Open example.com' );
	await dialog.getByRole( 'button', { name: 'Send' } ).click();
	await expect( dialog.getByRole( 'log' ) ).toContainText(
		'That page is not on this site.'
	);
	expect( sent.results[ 0 ] ).toMatchObject( {
		callId: 'away',
		result: { success: false },
	} );
	expect( new URL( page.url() ).searchParams.get( 'page_id' ) ).toBe(
		String( pageId )
	);

	await dialog.getByLabel( 'Your question' ).fill( 'Show me the grant' );
	await dialog.getByRole( 'button', { name: 'Send' } ).click();
	await page.waitForURL( `**/?p=${ seed.postId }` );
} );

test( 'with the setting on, every page has the assistant in a corner, and keeps the conversation', async ( {
	page,
	seed,
} ) => {
	launcher( true );
	await turing( page, [ grantAnswer( seed ) ] );

	// A page that holds the block gets no second one.
	await page.goto( `/?page_id=${ pageId }` );
	await expect( page.locator( '.viglet-dumont-assistant' ) ).toHaveCount( 1 );

	await page.goto( `/?page_id=${ seed.searchPageId }` );
	const corner = page.locator( '.viglet-dumont-assistant.is-floating' );
	await corner.getByRole( 'button', { name: 'Ask this site' } ).click();
	const dialog = page.getByRole( 'dialog', { name: 'Ask this site' } );
	await dialog
		.getByLabel( 'Your question' )
		.fill( 'When does the grant close?' );
	await dialog.getByRole( 'button', { name: 'Send' } ).click();
	const source = dialog.getByRole( 'link', { name: 'Research grant 2026' } );
	await source.click();
	await page.waitForURL( `**/?p=${ seed.postId }` );

	// On the post it cited, the conversation is still there.
	await page
		.locator( '.viglet-dumont-assistant.is-floating' )
		.getByRole( 'button', { name: 'Ask this site' } )
		.click();
	await expect(
		page.getByRole( 'dialog', { name: 'Ask this site' } ).getByRole( 'log' )
	).toContainText( 'Applications close on 14 March 2026.' );
} );
