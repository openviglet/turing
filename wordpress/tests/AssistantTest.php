<?php
/**
 * The Site assistant (D175): the first questions it suggests, its AI notice (T1369), and the
 * launcher only when the site asks for it.
 *
 * @package Viglet_Turing
 */

namespace Viglet\Turing\Tests;

use Brain\Monkey\Actions;
use Brain\Monkey\Filters;
use Brain\Monkey\Functions;
use Viglet_Turing_Assistant;

final class AssistantTest extends PluginTestCase {

	public function test_the_blocks_own_questions_come_first_one_per_line(): void {
		Functions\expect( 'get_transient' )->never();

		$suggestions = ( new Viglet_Turing_Assistant( $this->settings() ) )->suggestions( "When does the grant close?\n\n  Where is the meeting?  \nWhen does the grant close?" );

		$this->assertSame( array( 'When does the grant close?', 'Where is the meeting?' ), $suggestions );
	}

	public function test_without_its_own_the_block_suggests_the_weeks_popular_searches(): void {
		Functions\when( 'get_transient' )->justReturn( array( 'workshop', 'grant', 'meeting', 'tents', 'boots' ) );

		$suggestions = ( new Viglet_Turing_Assistant( $this->settings() ) )->suggestions( '' );

		$this->assertSame( array( 'workshop', 'grant', 'meeting', 'tents' ), $suggestions, 'at most four' );
	}

	public function test_the_ai_notice_names_the_sites_content_by_default(): void {
		$notice = ( new Viglet_Turing_Assistant( $this->settings() ) )->disclaimer( '' );

		$this->assertSame( 'Answers are generated by AI from this site’s content and may be wrong. Check the sources they cite.', $notice );
		$this->assertStringNotContainsString( 'post', $notice );
	}

	public function test_the_blocks_own_ai_notice_replaces_the_default(): void {
		$notice = ( new Viglet_Turing_Assistant( $this->settings() ) )->disclaimer( '  Answers from our pages; check the sources.  ' );

		$this->assertSame( 'Answers from our pages; check the sources.', $notice );
	}

	public function test_the_filter_has_the_last_word_on_the_ai_notice(): void {
		Filters\expectApplied( 'viglet_turing_assistant_disclaimer' )->once()->with( 'The block’s notice.' )->andReturn( 'The site’s notice.' );

		$notice = ( new Viglet_Turing_Assistant( $this->settings() ) )->disclaimer( 'The block’s notice.' );

		$this->assertSame( 'The site’s notice.', $notice );
	}

	public function test_an_empty_ai_notice_from_the_filter_keeps_the_default(): void {
		Filters\expectApplied( 'viglet_turing_assistant_disclaimer' )->once()->andReturn( '   ' );

		$notice = ( new Viglet_Turing_Assistant( $this->settings() ) )->disclaimer( '' );

		$this->assertSame( 'Answers are generated by AI from this site’s content and may be wrong. Check the sources they cite.', $notice );
	}

	public function test_the_launcher_is_off_until_the_site_turns_it_on(): void {
		Actions\expectAdded( 'wp_footer' )->never();
		( new Viglet_Turing_Assistant( $this->settings() ) )->register();

		$this->addToAssertionCount( 1 );
	}

	public function test_with_the_setting_on_every_page_gets_the_launcher(): void {
		$assistant = new Viglet_Turing_Assistant( $this->settings( array( 'assistant_launcher' => 1 ) ) );
		Actions\expectAdded( 'wp_enqueue_scripts' )->once()->with( array( $assistant, 'enqueue' ) );
		Actions\expectAdded( 'wp_footer' )->once()->with( array( $assistant, 'launcher' ), 5 );

		$assistant->register();

		$this->addToAssertionCount( 1 );
	}
}
