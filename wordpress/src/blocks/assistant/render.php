<?php
/**
 * The Site assistant block (D175), server side: a button that opens a chat with Turing over
 * this site's posts, driven by src/public/assistant.js. Hidden until Turing says chat is on.
 * Viglet_Dumont_Assistant renders it in a corner of every page too, with `floating`.
 *
 * @package Viglet_Dumont
 *
 * @var array $attributes The block's attributes.
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

$viglet_dumont_id          = wp_unique_id( 'viglet-dumont-assistant-' );
$viglet_dumont_heading     = '' !== (string) ( $attributes['heading'] ?? '' ) ? (string) $attributes['heading'] : __( 'Ask this site', 'viglet-dumont' );
$viglet_dumont_suggestions = ( new Viglet_Dumont_Assistant() )->suggestions( (string) ( $attributes['suggestions'] ?? '' ) );

wp_interactivity_state(
	'viglet-dumont/assistant',
	array(
		'available' => false,
		'question'  => '',
		'messages'  => array(),
		'streaming' => false,
		'status'    => '',
		'thinking'  => __( 'Reading this site’s posts…', 'viglet-dumont' ),
		'failed'    => __( 'The assistant could not answer right now. Try again in a moment.', 'viglet-dumont' ),
	)
);
?>
<div
	<?php echo get_block_wrapper_attributes( array( 'class' => 'viglet-dumont-assistant' . ( empty( $attributes['floating'] ) ? '' : ' is-floating' ) ) ); // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- core escapes the wrapper attributes. ?>
	data-wp-interactive="viglet-dumont/assistant"
	<?php
	echo wp_interactivity_data_wp_context( // phpcs:ignore WordPress.Security.EscapeOutput.OutputNotEscaped -- core escapes the context.
		array(
			'suggestions' => array_map(
				static fn ( string $text ) => array(
					'key'  => $text,
					'text' => $text,
				),
				$viglet_dumont_suggestions
			),
		)
	);
	?>
	data-wp-init="callbacks.init"
	hidden
	data-wp-bind--hidden="!state.available"
>
	<button type="button" class="wp-element-button viglet-dumont-assistant__open" aria-haspopup="dialog" data-wp-on--click="actions.open"><?php echo esc_html( $viglet_dumont_heading ); ?></button>
	<dialog class="viglet-dumont-assistant__dialog" aria-labelledby="<?php echo esc_attr( $viglet_dumont_id ); ?>-heading" data-wp-on--click="actions.backdrop">
		<div class="viglet-dumont-assistant__head">
			<h2 id="<?php echo esc_attr( $viglet_dumont_id ); ?>-heading"><?php echo esc_html( $viglet_dumont_heading ); ?></h2>
			<button type="button" class="viglet-dumont-assistant__restart" data-wp-on--click="actions.restart" data-wp-bind--disabled="!state.messages.length"><?php esc_html_e( 'New conversation', 'viglet-dumont' ); ?></button>
			<button type="button" class="viglet-dumont-assistant__close" data-wp-on--click="actions.close" aria-label="<?php esc_attr_e( 'Close', 'viglet-dumont' ); ?>">&times;</button>
		</div>
		<p class="viglet-dumont-assistant__generated"><?php esc_html_e( 'Answers are generated by AI from this site’s posts and may be wrong. Check the posts they cite.', 'viglet-dumont' ); ?></p>
		<div class="viglet-dumont-assistant__log" role="log" aria-label="<?php esc_attr_e( 'Conversation', 'viglet-dumont' ); ?>" data-wp-bind--aria-busy="state.streaming"><ol>
			<template data-wp-each--message="state.messages" data-wp-each-key="context.message.id">
				<li class="viglet-dumont-assistant__message" data-wp-class--is-visitor="context.message.visitor">
					<p class="viglet-dumont-assistant__text" data-wp-text="context.message.text"></p>
					<ul class="viglet-dumont-assistant__sources" aria-label="<?php esc_attr_e( 'Posts it used', 'viglet-dumont' ); ?>" hidden data-wp-bind--hidden="!context.message.sources.length">
						<template data-wp-each--source="context.message.sources" data-wp-each-key="context.source.url">
							<li class="viglet-dumont-assistant__source"><a data-wp-bind--href="context.source.url" data-wp-text="context.source.title"></a></li>
						</template>
					</ul>
					<p class="viglet-dumont-assistant__feedback" hidden data-wp-bind--hidden="!context.message.canRate">
						<?php esc_html_e( 'Was this helpful?', 'viglet-dumont' ); ?>
						<button type="button" data-wp-on--click="actions.helpful"><?php esc_html_e( 'Yes', 'viglet-dumont' ); ?></button>
						<button type="button" data-wp-on--click="actions.notHelpful"><?php esc_html_e( 'No', 'viglet-dumont' ); ?></button>
					</p>
					<p class="viglet-dumont-assistant__feedback" role="status" hidden data-wp-bind--hidden="!context.message.rated"><?php esc_html_e( 'Thank you.', 'viglet-dumont' ); ?></p>
				</li>
			</template>
		</ol></div>
		<div class="viglet-dumont-assistant__suggestions" hidden data-wp-bind--hidden="!state.suggesting">
			<p><?php esc_html_e( 'Try asking', 'viglet-dumont' ); ?></p>
			<ul>
				<template data-wp-each--suggestion="context.suggestions" data-wp-each-key="context.suggestion.key">
					<li><button type="button" data-wp-on--click="actions.suggest" data-wp-text="context.suggestion.text"></button></li>
				</template>
			</ul>
		</div>
		<form class="viglet-dumont-assistant__form" data-wp-on--submit="actions.ask">
			<label for="<?php echo esc_attr( $viglet_dumont_id ); ?>"><?php esc_html_e( 'Your question', 'viglet-dumont' ); ?></label>
			<input
				type="text"
				id="<?php echo esc_attr( $viglet_dumont_id ); ?>"
				autocomplete="off"
				data-wp-bind--value="state.question"
				data-wp-on--input="actions.type"
			/>
			<button type="submit" class="wp-element-button" data-wp-bind--disabled="state.streaming"><?php esc_html_e( 'Send', 'viglet-dumont' ); ?></button>
		</form>
		<p class="viglet-dumont-assistant__status" role="status" data-wp-text="state.status"></p>
	</dialog>
</div>
