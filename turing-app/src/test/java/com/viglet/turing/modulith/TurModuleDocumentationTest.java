package com.viglet.turing.modulith;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.List;
import java.util.stream.StreamSupport;

import org.junit.jupiter.api.Test;
import org.springframework.modulith.core.ApplicationModule;
import org.springframework.modulith.core.ApplicationModules;
import org.springframework.modulith.docs.Documenter;

/**
 * T1326 / ADR 0005 — module documentation generated from the verified model, so nobody
 * redraws it. Spring Modulith's Documenter writes the C4 component diagrams (PlantUML)
 * and a canvas per module into {@code target/spring-modulith-docs}. The contributor page
 * {@code docs/architecture/modules.md} holds the module list and a Mermaid graph of their
 * dependencies, which GitHub renders; this test regenerates it and fails when the
 * committed page differs, writing the new one in place so a commit picks it up.
 *
 * @author Alexandre Oliveira
 * @since 2026.3.8
 */
class TurModuleDocumentationTest {

    /** The contributor page, from the turing-app module the build runs in. */
    static final Path PAGE = Path.of("..", "docs", "architecture", "modules.md");

    @Test
    void theDiagramsAreGeneratedIntoTheBuild() {
        new Documenter(TurModules.model()).writeDocumentation();

        assertThat(Path.of("target", "spring-modulith-docs", "components.puml")).exists();
        assertThat(Path.of("target", "spring-modulith-docs", "module-sn.puml")).exists();
    }

    @Test
    void theContributorPageMatchesTheModel() throws IOException {
        String expected = page(TurModules.model());
        String committed = Files.exists(PAGE) ? Files.readString(PAGE, StandardCharsets.UTF_8) : "";
        if (!committed.replace("\r\n", "\n").equals(expected)) {
            Files.createDirectories(PAGE.getParent());
            Files.writeString(PAGE, expected, StandardCharsets.UTF_8);
        }
        assertThat(committed.replace("\r\n", "\n"))
                .as("docs/architecture/modules.md was stale and has been regenerated: commit it")
                .isEqualTo(expected);
    }

    static String page(ApplicationModules modules) {
        List<ApplicationModule> ordered = StreamSupport.stream(modules.spliterator(), false)
                .sorted(Comparator.comparing(module -> module.getIdentifier().toString()))
                .toList();
        StringBuilder page = new StringBuilder();
        page.append("<!-- Generated by TurModuleDocumentationTest from the verified module model;")
                .append(" do not edit. Run `mvn test -pl turing-app -Dtest=TurModuleDocumentationTest`")
                .append(" to regenerate. -->\n\n");
        page.append("# Backend modules\n\n");
        page.append("The backend is a modular monolith ([ADR 0005](../adr/0005-modular-monolith-spring-modulith.md)):")
                .append(" each direct sub-package of `com.viglet.turing` is a module, and `mvn test` fails on a")
                .append(" cycle, a call into another module's internal package or a dependency a module does")
                .append(" not declare. The C4 component diagrams and a canvas per module are generated into")
                .append(" `turing-app/target/spring-modulith-docs` by the same test.\n\n");
        page.append("## Dependencies\n\n");
        page.append("An arrow points from a module to one it uses. Every module may use `shared`, so those")
                .append(" arrows are left out.\n\n");
        page.append("```mermaid\nflowchart BT\n");
        for (ApplicationModule module : ordered) {
            page.append("    ").append(module.getIdentifier()).append("[\"").append(module.getDisplayName())
                    .append("<br/><code>").append(module.getIdentifier()).append("</code>\"]\n");
        }
        for (ApplicationModule module : ordered) {
            for (String target : dependencies(module, modules)) {
                if (!"shared".equals(target)) {
                    page.append("    ").append(module.getIdentifier()).append(" --> ").append(target).append('\n');
                }
            }
        }
        page.append("```\n\n");
        page.append("## Modules\n\n");
        page.append("| Module | Name | Uses |\n|---|---|---|\n");
        for (ApplicationModule module : ordered) {
            List<String> uses = dependencies(module, modules);
            page.append("| `").append(module.getIdentifier()).append("` | ").append(module.getDisplayName())
                    .append(" | ").append(uses.isEmpty() ? "nothing" : String.join(", ", uses.stream()
                            .map(use -> "`" + use + "`").toList()))
                    .append(" |\n");
        }
        return page.toString();
    }

    private static List<String> dependencies(ApplicationModule module, ApplicationModules modules) {
        return module.getDirectDependencies(modules).uniqueModules()
                .map(dependency -> dependency.getIdentifier().toString())
                .distinct()
                .sorted()
                .toList();
    }
}
